#!/usr/bin/env python3
"""Compile GLSL 460 Vulkan 1.3 shaders into embedded C++ SPIR-V arrays (vk_shaders_spv.hpp)."""
from __future__ import annotations

import pathlib
import shutil
import struct
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "vk_shaders_spv.hpp"

SHADERS = [
    ("kPresentVertSpv", "present.vert"),
    ("kPresentFragSpv", "present.frag"),
    ("kOverlayFragSpv", "overlay.frag"),
    ("kBlurVertSpv", "blur.vert"),
    ("kBlurFragSpv", "blur.frag"),
    ("kGeDrawVertSpv", "ge_draw.vert"),
    ("kGeDrawFragSpv", "ge_draw.frag"),
    ("kShadowMapVertSpv", "shadow_map.vert"),
    ("kShadowMapFragSpv", "shadow_map.frag"),
    ("kShadowFactorCompSpv", "shadow_factor.comp"),
    ("kShadowApplyCompSpv", "shadow_apply.comp"),
    ("kPlaceV2CompSpv", "place_v2.comp"),
    ("kGtaoCompSpv", "gtao.comp"),
    ("kGtaoDenoiseCompSpv", "gtao_denoise.comp"),
    ("kVolumetricFogCompSpv", "volumetric_fog.comp"),
    ("kBloomExtractCompSpv", "bloom_extract.comp"),
    ("kSsgiBounceCompSpv", "ssgi_bounce.comp"),
    ("kGlowBlurCompSpv", "glow_blur.comp"),
    ("kEmissiveFlashCompSpv", "emissive_flash.comp"),
    ("kLightingCompositeCompSpv", "lighting_composite.comp"),
    ("kFxaaPrehudCompSpv", "fxaa_prehud.comp"),
    ("kTaaResolveCompSpv", "taa_resolve.comp"),
]


def compile_shader(glslc: str, src: pathlib.Path) -> list[int]:
    with tempfile.NamedTemporaryFile(suffix=".spv", delete=False) as tmp:
        spv_path = pathlib.Path(tmp.name)
    try:
        cmd = [glslc, "--target-env=vulkan1.3", "-O", str(src), "-o", str(spv_path)]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"error compiling {src.name}:\n{res.stderr}", file=sys.stderr)
            raise SystemExit(1)
        data = spv_path.read_bytes()
        if len(data) % 4 != 0:
            raise SystemExit(f"error: {src.name} SPIR-V size {len(data)} is not a multiple of 4")
        return list(struct.unpack(f"<{len(data) // 4}I", data))
    finally:
        spv_path.unlink(missing_ok=True)


def main() -> int:
    glslc = shutil.which("glslc")
    if not glslc:
        print("error: glslc not found in PATH", file=sys.stderr)
        return 1

    lines = [
        "#pragma once",
        "// Auto-generated by platforms/psp/frontend/vulkan/shaders/compile.py — do not edit by hand.",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace mhf::psp::vk::shaders {",
        "",
    ]
    for symbol, filename in SHADERS:
        words = compile_shader(glslc, HERE / filename)
        lines.append(f"inline constexpr std::array<std::uint32_t, {len(words)}> {symbol} = {{")
        for i in range(0, len(words), 8):
            chunk = ", ".join(f"0x{w:08X}u" for w in words[i : i + 8])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
    lines.append("} // namespace mhf::psp::vk::shaders")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(SHADERS)} shaders)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
